// tools/build-system-prompt.mjs
// 把仓库根 travel-agent.md（唯一行为真值源）编译成 Worker 可直接 import 的模块。
// 零依赖、幂等：同一份 travel-agent.md 永远生成字节完全一致的 worker/src/prompt.js。
//
//   node tools/build-system-prompt.mjs
//
// 为什么用 JSON.stringify 包一层：
//   - 生成的是合法 JS，也是合法 JSON 字符串字面量；
//   - 换行 / 反斜杠 / 引号 / 中文全部转义正确，Worker 与 Python(json.loads) 都能无损还原；
//   - examples/regress.py 的 [K] 只需抽出这一行、json.loads 后与 travel-agent.md 逐字节比对，
//     就能保证「改了提示词却忘了重新生成 prompt.js」立刻被门禁抓住。

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, "..");
const SRC = resolve(ROOT, "travel-agent.md");
const OUT = resolve(ROOT, "worker", "src", "prompt.js");

// 按原始字节解码，不做换行转换（Windows CRLF 原样保留），
// 这样与 Python 侧 read_bytes().decode("utf-8") 的比对才是真正的逐字节一致。
const text = readFileSync(SRC).toString("utf8");

const header = [
  "// AUTO-GENERATED by tools/build-system-prompt.mjs — DO NOT EDIT BY HAND.",
  "// Single source of truth: travel-agent.md at repository root.",
  "// Regenerate after any prompt change: node tools/build-system-prompt.mjs",
  "// examples/regress.py [K] compares the embedded string with travel-agent.md.",
  "",
].join("\n");

// JSON.stringify 产出单行、可被 Python json.loads 无损还原的字符串字面量。
const body = `export const PROMPT = ${JSON.stringify(text)};\n`;
const output = header + body;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, output, "utf8");

process.stdout.write(
  `OK: ${OUT}\n` +
    `    source bytes = ${Buffer.byteLength(text, "utf8")}, ` +
    `prompt.js bytes = ${Buffer.byteLength(output, "utf8")}\n`
);
